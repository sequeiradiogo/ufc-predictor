def compute_priors(conn: sqlite3.Connection, stats=None, start: str = PRIOR_START,
                   end: str = PRIOR_END, by_division: bool = False):
    """Rounds-weighted mean of each stat over per-corner pre-fight snapshots in [start, end].

    Weighting by total_rounds_fought gives debut rows (0 rounds, stats stored as 0) no
    weight. by_division=True returns {division: {stat: mean}} for the divisions with at
    least DIV_MIN_ROWS rows.
    """
    stats = list(stats or PRIORS)
    fs = pd.read_sql_query(
        f"SELECT f.division, fs.total_rounds_fought, {', '.join('fs.' + s for s in stats)} "
        "FROM fight_stats fs JOIN fights f USING (fight_id) WHERE f.date BETWEEN ? AND ?",
        conn, params=(start, end),
    )

    def _means(g: pd.DataFrame) -> dict[str, float]:
        w = pd.to_numeric(g["total_rounds_fought"], errors="coerce").fillna(0).clip(lower=0)
        out = {}
        for s in stats:
            v = pd.to_numeric(g[s], errors="coerce")
            m = v.notna() & (w > 0)
            if m.any():
                out[s] = float(np.average(v[m], weights=w[m]))
        return out

    if not by_division:
        return _means(fs)
    fs["division"] = fs["division"].map(_norm_div)
    w = pd.to_numeric(fs["total_rounds_fought"], errors="coerce").fillna(0)
    return {d: _means(g) for d, g in fs[w > 0].groupby("division")
            if d and len(g) >= DIV_MIN_ROWS}


# -- Which settings a model was trained with -----------------------------------
# config.SHRINK_K / SHRINK_BY_DIVISION only decide how ML_data_preparation_v1.py
# builds the training CSV. Live inference must shrink exactly as the loaded model
# was trained, not as config.py says today: flipping the config before a retrain
# would otherwise feed shrunk features to a model trained on raw ones, silently.
# So the CSV build records its settings in a sidecar, training copies them into
# the tier directory (a .joblib, so the release tarballs carry it), and predict.py
# reads them from there -- a tier without the file means shrinkage off.
SETTINGS_NAME = "feature_settings.joblib"
OFF = {"shrink_k": 0.0, "shrink_by_division": False}


def config_settings() -> dict:
    from config import SHRINK_BY_DIVISION, SHRINK_K
    return {"shrink_k": float(SHRINK_K), "shrink_by_division": bool(SHRINK_BY_DIVISION)}


def csv_settings_path(csv_path: Path) -> Path:
    """Sidecar recording how a feature CSV was built (next to the CSV)."""
    return csv_path.with_name(csv_path.stem + ".settings.joblib")


def read_settings(path: Path) -> dict:
    """Settings stored at *path*; OFF when the file doesn't exist (artifacts from before 2026-11)."""
    if not Path(path).exists():
        return dict(OFF)
    return {**OFF, **joblib.load(path)}


def write_settings(path: Path, settings: dict) -> None:
    joblib.dump({k: settings[k] for k in OFF}, path)


def stamp_models_dir(models_dir: Path, settings: dict, partial: bool) -> None:
    """Record *settings* in a tier directory. A partial retrain (one model only) must
    use the same settings as the models already there, or the tier would mix them."""
    path = Path(models_dir) / SETTINGS_NAME
    if partial and path.exists() and read_settings(path) != {k: settings[k] for k in OFF}:
        raise SystemExit(
            f"Feature settings {settings} differ from the ones {models_dir.name}/ was trained with "
            f"({read_settings(path)}). Retrain every model (no --model) after changing "
            "SHRINK_K / SHRINK_BY_DIVISION."
        )
    write_settings(path, settings)


def _norm_div(division) -> str:
    return str(division or "").lower().strip()


def _by_division(by_division: bool | None) -> bool:
    if by_division is None:
        from config import SHRINK_BY_DIVISION
        by_division = SHRINK_BY_DIVISION
    return bool(by_division)


def priors_for(division=None, by_division: bool | None = None) -> dict[str, float]:
    """The priors used for one fight: the division's, falling back to PRIORS per stat."""
    if not _by_division(by_division):
        return PRIORS
    return {**PRIORS, **DIV_PRIORS.get(_norm_div(division), {})}


def _k(k: float | None) -> float:
    if k is None:
        from config import SHRINK_K
        k = SHRINK_K
    return float(k)


def shrink(value, rounds, prior: float, k: float):
    """(value * rounds + prior * k) / (rounds + k); scalars or arrays. NaN values stay NaN."""
    rounds = np.clip(np.asarray(rounds, dtype=float), 0, None)
    rounds = np.where(np.isnan(rounds), 0.0, rounds)
    out = (np.asarray(value, dtype=float) * rounds + prior * k) / (rounds + k)
    return float(out) if np.ndim(out) == 0 else out


def shrink_corner(stats, rounds, k: float | None = None, division=None,
                  by_division: bool | None = None):
    """Copy of one fighter's stats (dict or Series) with every PRIORS key present shrunk.

    Missing keys stay missing, so callers' own defaults still apply. *division* is the
    division of the fight being predicted (used when shrinking by division).
    """
    k = _k(k)
    if k <= 0 or stats is None:
        return stats
    out = stats.copy() if isinstance(stats, pd.Series) else dict(stats)
    r = float(pd.to_numeric(rounds, errors="coerce") or 0.0)
    for s, prior in priors_for(division, by_division).items():
        if s in out:
            v = pd.to_numeric(out[s], errors="coerce")
            if v is not None and not pd.isna(v):
                out[s] = shrink(float(v), r, prior, k)
    return out


def shrink_wide(wide: pd.DataFrame, k: float | None = None,
                by_division: bool | None = None) -> pd.DataFrame:
    """Shrink r_<stat> / b_<stat> columns of a one-row-per-fight frame in place (returns it).

    Reads the fight's division from wide["division"] when shrinking by division.
    """
    k = _k(k)
    if k <= 0:
        return wide
    by_div = _by_division(by_division)
    divs = wide["division"].map(_norm_div) if by_div and "division" in wide.columns else None
    for corner in ("r", "b"):
        rounds = pd.to_numeric(wide.get(f"{corner}_total_rounds_fought"), errors="coerce").fillna(0).values
        for s, prior in PRIORS.items():
            col = f"{corner}_{s}"
            if col not in wide.columns:
                continue
            if divs is not None:
                prior = divs.map(lambda d: DIV_PRIORS.get(d, {}).get(s, PRIORS[s])).values.astype(float)
            wide[col] = shrink(pd.to_numeric(wide[col], errors="coerce").values, rounds, prior, k)
    return wide
