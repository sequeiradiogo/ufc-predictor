log = get_logger(__name__)


def _load_csv() -> pd.DataFrame:
    if not CSV_V1_WITH_ELO.exists():
        log.error(
            "v1 feature CSV not found at '%s'. "
            "Run: python ml/ML_data_preparation_v1.py",
            CSV_V1_WITH_ELO,
        )
        sys.exit(1)
    df = pd.read_csv(CSV_V1_WITH_ELO)
    df["date"] = pd.to_datetime(df["date"])
    df = df.sort_values("date").reset_index(drop=True)
    log.info("Loaded %d rows from %s", len(df), CSV_V1_WITH_ELO.name)
    return df


def _score(df: pd.DataFrame, model_type: str) -> pd.DataFrame:
    specs = {
        "xgb":  (MODEL_V1_XGB_PATH,  MODEL_V1_XGB_FEATURES,  None,               False),
        "lr":   (MODEL_V1_LR_PATH,   MODEL_V1_LR_FEATURES,   MODEL_V1_LR_SCALER, True),
        "rf":   (MODEL_V1_RF_PATH,   MODEL_V1_RF_FEATURES,   None,               False),
        "lgbm": (MODEL_V1_LGBM_PATH, MODEL_V1_LGBM_FEATURES, None,               False),
        "mlp":  (MODEL_V1_MLP_PATH,  MODEL_V1_MLP_FEATURES,  MODEL_V1_MLP_SCALER, True),
    }

    if model_type == "ensemble":
        return _score_ensemble(df)
    if model_type == "stacking":
        return _score_stacking(df)

    m_path, f_path, s_path, is_lr = specs[model_type]
    artifact  = joblib.load(m_path)
    feat_names = joblib.load(f_path)
    scaler    = joblib.load(s_path) if s_path and s_path.exists() else None

    X    = df.reindex(columns=feat_names, fill_value=0).fillna(0)
    base = artifact["base"] if is_lr else artifact
    raw  = symmetric_proba(lambda Z: base.predict_proba(scaler.transform(Z) if scaler else Z.values)[:, 1], X)
    if not is_lr:
        return _make_results(df, raw)
    # LR / MLP: the stored calibrator (Platt / isotonic) is part of the model,
    # as in predict.py -- scoring the raw base probability graded another rule
    platt = artifact["platt"]
    if hasattr(platt, "predict_proba"):
        prob_red = platt.predict_proba(raw.reshape(-1, 1))[:, 1]
    else:
        prob_red = platt.predict(raw)
    return _make_results(df, prob_red)


def _score_ensemble(df: pd.DataFrame) -> pd.DataFrame:
    ens         = joblib.load(MODEL_V1_ENSEMBLE_PATH)
    weights     = ens.get("weights", {})
    calibrators = ens.get("calibrators", {})

    specs = [
        ("xgb",  MODEL_V1_XGB_PATH,  MODEL_V1_XGB_FEATURES,  None,               False),
        ("lr",   MODEL_V1_LR_PATH,   MODEL_V1_LR_FEATURES,   MODEL_V1_LR_SCALER, True),
        ("rf",   MODEL_V1_RF_PATH,   MODEL_V1_RF_FEATURES,   None,               False),
        ("lgbm", MODEL_V1_LGBM_PATH, MODEL_V1_LGBM_FEATURES, None,               False),
        ("mlp",  MODEL_V1_MLP_PATH,  MODEL_V1_MLP_FEATURES,  MODEL_V1_MLP_SCALER, True),
    ]

    model_probas   = []
    active_weights = []

    for m_key, m_path, f_path, s_path, is_lr in specs:
        if not m_path.exists() or not f_path.exists() or m_key not in weights:
            continue
        artifact  = joblib.load(m_path)
        feat_names = joblib.load(f_path)
        scaler    = joblib.load(s_path) if s_path and s_path.exists() else None

        X  = df.reindex(columns=feat_names, fill_value=0).fillna(0)
        base = artifact["base"] if is_lr else artifact
        raw_p = symmetric_proba(
            lambda Z, b=base, s=scaler: b.predict_proba(s.transform(Z) if s else Z.values)[:, 1], X)

        cal_p = calibrators[m_key].predict(raw_p) if m_key in calibrators else raw_p

        model_probas.append(cal_p)
        active_weights.append(weights[m_key])

    total_w = sum(active_weights)
    active_weights = [w / total_w for w in active_weights]
    prob_red = np.average(model_probas, axis=0, weights=active_weights)
    prob_red = apply_temperature(prob_red, ens.get("temperature", 1.0))
    return _make_results(df, prob_red)


def _score_stacking(df: pd.DataFrame) -> pd.DataFrame:
    stk        = joblib.load(MODEL_V1_STACKING_PATH)
    meta_lr    = stk["meta"]
    meta_sc    = stk["meta_scaler"]
    stk_specs  = stk.get("specs", [])

    base_probs = []
    for m_key, m_path, f_path, s_path, is_lr in stk_specs:
        # Next to stacking.joblib (older artifacts stored absolute paths)
        m_path = MODEL_V1_STACKING_PATH.parent / Path(m_path).name
        f_path = MODEL_V1_STACKING_PATH.parent / Path(f_path).name
        s_path = MODEL_V1_STACKING_PATH.parent / Path(s_path).name if s_path else None
        if not m_path.exists() or not f_path.exists():
            log.warning("Stacking backtest: base model %s not found, using 0.5", m_key)
            base_probs.append(np.full(len(df), 0.5))
            continue
        artifact   = joblib.load(m_path)
        feat_names = joblib.load(f_path)
        scaler     = joblib.load(s_path) if s_path and s_path.exists() else None

        X  = df.reindex(columns=feat_names, fill_value=0).fillna(0)
        base = artifact["base"] if is_lr else artifact
        raw_p = symmetric_proba(
            lambda Z, b=base, s=scaler: b.predict_proba(s.transform(Z) if s else Z.values)[:, 1], X)
        base_probs.append(raw_p)

    stacked   = np.column_stack(base_probs)
    stacked_s = meta_sc.transform(stacked)
    prob_red  = meta_lr.predict_proba(stacked_s)[:, 1]
    return _make_results(df, prob_red)


def _make_results(df: pd.DataFrame, prob_red: np.ndarray) -> pd.DataFrame:
    predicted = (prob_red >= 0.5).astype(int)
    return pd.DataFrame({
        "fight_id":  df["fight_id"].values,
        "date":      df["date"].values,
        "year":      df["date"].dt.year.values,
        "target":    df[TARGET_COL].values,
        "predicted": predicted,
        "correct":   (df[TARGET_COL].values == predicted).astype(int),
        "prob_red":  prob_red,
    })


def _print_report(results: pd.DataFrame, label: str, from_year: int | None) -> None:
    subset = results[results["year"] >= from_year] if from_year else results
    if subset.empty:
        print(f"  No fights found from {from_year}+.")
        return

    print(f"\n  {label}  |  from_year={from_year or 'all'}")
    print("-" * 40)

    for yr, grp in subset.groupby("year"):
        acc = grp["correct"].mean()
        n   = len(grp)
        print(f"  {yr}  {n:>6} fights  {acc:.1%}")

    acc_total = subset["correct"].mean()
    n_total   = len(subset)
    print(f"\n  Total  {n_total:>6} fights  {acc_total:.1%}")

    # Same windows as train_v1_models.py: base models and calibrators are fit
    # before `split`; nothing is fit after it (the ensemble is the plain mean of
    # the calibrated models since issue #73 -- until 2026-11 its weights and
    # temperature were fit on the first half). The hold-out (second half) is
    # kept as its own row to stay comparable with earlier figures.
    n      = len(results)
    split  = int(n * TRAIN_TEST_SPLIT)
    hold   = split + (n - split) // 2
    pos    = subset.index.values   # results has a RangeIndex in date order
    print("\n  By eval-tier window:")
    for name, lo, hi in [("fit / calibration", 0, split),
                         ("test, first half", split, hold),
                         ("hold-out", hold, n)]:
        win = subset[(pos >= lo) & (pos < hi)]
        if win.empty:
            continue
        span = f"{win['date'].min().date()} to {win['date'].max().date()}"
        print(f"  {name:<18} {span}  {len(win):>5} fights  {win['correct'].mean():.1%}")
    print("  (everything from the test window on is out of sample, for the ensemble and\n"
          "   every single model -- valid for models trained after issue #73)")
    print()


# Buckets on the less experienced fighter's prior UFC fights (wins + losses
# before the fight, as stored in ufc_v2.db). Debuts aren't in the CSV.
EXPERIENCE_BUCKETS = [(1, 1, "1"), (2, 3, "2-3"), (4, 5, "4-5"), (6, 10**6, "6+")]


def _implied(odds: pd.Series) -> pd.Series:
    """American moneyline -> implied probability (vig included)."""
    o = pd.to_numeric(odds, errors="coerce")
    return np.where(o < 0, -o / (-o + 100), 100 / (o + 100))


def _experience_frame() -> pd.DataFrame:
    """fight_id -> min prior UFC fights of the two corners + de-vigged market prob."""
    with sqlite3.connect(f"file:{DB_V1_PATH}?mode=ro", uri=True) as conn:
        fx = pd.read_sql(
            """SELECT f.fight_id, f.odds_red, f.odds_blue,
                      r.wins + r.losses AS r_exp, b.wins + b.losses AS b_exp
               FROM fights f
               JOIN fight_stats r ON r.fight_id = f.fight_id AND r.fighter_id = f.r_fighter_id
               JOIN fight_stats b ON b.fight_id = f.fight_id AND b.fighter_id = f.b_fighter_id""",
            conn)
    fx["min_exp"] = fx[["r_exp", "b_exp"]].min(axis=1)
    pr, pb = _implied(fx["odds_red"]), _implied(fx["odds_blue"])
    fx["market_red"] = pr / (pr + pb)   # NaN when either side has no price
    return fx[["fight_id", "min_exp", "market_red"]]


def _log_loss(y: np.ndarray, p: np.ndarray) -> float:
    p = np.clip(p, 1e-6, 1 - 1e-6)
    return float(-np.mean(y * np.log(p) + (1 - y) * np.log(1 - p)))


def _print_experience_report(results: pd.DataFrame, from_year: int | None) -> None:
    """Model vs bookmaker favorite, split by the less experienced fighter's UFC fights.

    Compared on the fights that have odds for both corners (a pick'em -- equal
    prices -- counts as a Red pick, like the model's exact 50%).
    """
    n     = len(results)
    split = int(n * TRAIN_TEST_SPLIT)
    hold  = split + (n - split) // 2
    res   = results.assign(pos=np.arange(n)).merge(_experience_frame(), on="fight_id", how="left")
    subset = res[res["year"] >= from_year] if from_year else res

    for title, frame in [(f"from_year={from_year or 'all'}", subset),
                         ("hold-out window only", subset[subset["pos"] >= hold])]:
        print(f"\n  By UFC experience (min prior UFC fights of the two corners) | {title}")
        print(f"  {'bucket':<6} {'fights':>6} {'model':>7} {'logloss':>8} | "
              f"{'w/odds':>6} {'model':>7} {'fav':>7} {'gap':>7} {'ll model':>9} {'ll mkt':>7}")
        rows = [(lbl, frame[frame["min_exp"].between(lo, hi)]) for lo, hi, lbl in EXPERIENCE_BUCKETS]
        rows.append(("all", frame[frame["min_exp"].notna()]))
        for lbl, g in rows:
            if g.empty:
                continue
            y = g["target"].values
            line = (f"  {lbl:<6} {len(g):>6} {g['correct'].mean():>7.1%} "
                    f"{_log_loss(y, g['prob_red'].values):>8.4f} | ")
            o = g[g["market_red"].notna()]
            if len(o):
                yo  = o["target"].values
                fav = ((o["market_red"].values >= 0.5).astype(int) == yo).mean()
                acc = o["correct"].mean()
                line += (f"{len(o):>6} {acc:>7.1%} {fav:>7.1%} {acc - fav:>+7.1%} "
                         f"{_log_loss(yo, o['prob_red'].values):>9.4f} "
                         f"{_log_loss(yo, o['market_red'].values):>7.4f}")
            print(line)
    print("  (gap = model accuracy - bookmaker favorite accuracy on the same fights;\n"
          "   ll mkt = log-loss of the de-vigged closing line)")
    print()


def main() -> None:
    parser = argparse.ArgumentParser(description="Backtest v1 (mdabbert) models.")
    parser.add_argument("--from-year", type=int, default=None)
    parser.add_argument("--model", choices=["xgb", "lr", "rf", "lgbm", "mlp", "ensemble", "stacking"],
                        default="ensemble")
    parser.add_argument("--by-experience", action="store_true",
                        help="also split accuracy by the less experienced fighter's prior UFC "
                             "fights, against the bookmaker favorite on the same fights")
    args = parser.parse_args()

    if not MODELS_V1_DIR.exists():
        print(f"[ERROR] v1 models not found at '{MODELS_V1_DIR}'.")
        sys.exit(1)

    df      = _load_csv()
    results = _score(df, args.model)
    _print_report(results, f"v1 {args.model}", args.from_year)
    if args.by_experience:
        _print_experience_report(results, args.from_year)


if __name__ == "__main__":
    main()
